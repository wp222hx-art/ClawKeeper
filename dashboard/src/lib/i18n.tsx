export type TranslationKey = keyof typeof dict.en;

// ---------------------------------------------------------------------------
// Context + provider
// ---------------------------------------------------------------------------
interface I18nContextValue {
  locale: Locale;
  set_locale: (l: Locale) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function detect_initial_locale(): Locale {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh') return stored;
  } catch {
    /* localStorage unavailable */
  }
  if (typeof navigator !== 'undefined' && /^zh\b/i.test(navigator.language)) return 'zh';
  return 'en';
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, set_locale_state] = useState<Locale>(() => detect_initial_locale());

  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, locale); } catch { /* ignore */ }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = locale === 'zh' ? 'zh-Hans' : 'en';
    }
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    set_locale: set_locale_state,
    t: (key, vars) => {
      const table = dict[locale] as Record<string, string>;
      const fallback = dict.en as Record<string, string>;
      const raw = table[key] ?? fallback[key] ?? key;
      if (!vars) return raw;
      return raw.replace(/\{(\w+)\}/g, (_m, k: string) =>
        vars[k] !== undefined ? String(vars[k]) : `{${k}}`,
      );
    },
  }), [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

// ---------------------------------------------------------------------------
// Hooks
// ---------------------------------------------------------------------------
export function useT() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useT must be used inside <LanguageProvider>');
  return ctx.t;
}

export function useLocale(): { locale: Locale; set_locale: (l: Locale) => void } {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useLocale must be used inside <LanguageProvider>');
  return { locale: ctx.locale, set_locale: ctx.set_locale };
}

